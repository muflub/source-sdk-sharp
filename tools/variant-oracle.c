static void quoted( const char *s )
{
	putchar( '"' );
	for ( ; *s; s++ )
	{
		if ( *s == '"' || *s == '\\' )
		{
			putchar( '\\' );
			putchar( *s );
		}
		else if ( *s == '\t' )
		{
			putchar( '\\' );
			putchar( 't' );
		}
		else if ( *s == '\n' )
		{
			putchar( '\\' );
			putchar( 'n' );
		}
		else
			putchar( *s );
	}
	putchar( '"' );
}

/* %.9g round-trips a float exactly; inf and nan get a spelling both readers
   agree on rather than whatever the platform prints. */
static void exact( float f )
{
	if ( isnan( f ) )
	{
		fputs( "nan", stdout );
		return;
	}
	if ( isinf( f ) )
	{
		fputs( f > 0 ? "inf" : "-inf", stdout );
		return;
	}
	printf( "%.9g", (double)f );
}

int main( void )
{
	unsigned i;

	puts( "# variant_convert_cases.tsv -- GENERATED by tools/variant-oracle.c." );
	puts( "#" );
	puts( "# What stock's variant_t answers about a map's text, from the glibc this" );
	puts( "# game links against." );
	puts( "#" );
	puts( "# REGENERATE IT INSIDE THE SNIPER CONTAINER, NEVER ON THE HOST. The two" );
	puts( "# glibcs disagree, and they disagree here: sscanf(\"1e\", \"%f\") assigns 1" );
	puts( "# under the container's 2.31 and assigns NOTHING under a modern host one," );
	puts( "# so a table generated on the host makes the vector column wrong for every" );
	puts( "# truncated exponent. The game and src/buildcpptests both build in the" );
	puts( "# container, so the container is the authority." );
	puts( "#" );
	puts( "#   podman run --rm --userns=keep-id \\" );
	puts( "#     --mount type=bind,source=\"$PWD\",target=/my_mod \\" );
	puts( "#     registry.gitlab.steamos.cloud/steamrt/sniper/sdk:latest bash -c \\" );
	puts( "#     'gcc -O0 -o /tmp/o /my_mod/tools/variant-oracle.c -lm && /tmp/o' \\" );
	puts( "#     > src/sourcesharp/test/variant_convert_cases.tsv" );
	puts( "#" );
	puts( "# Read by BOTH sides, deliberately: variant_convert_test.cpp recomputes" );
	puts( "# every column with the real libc, and VariantAgreementTests recomputes" );
	puts( "# every column with SourceSharp.Abi.VariantParse. VariantParse is a" );
	puts( "# stand-in for native code and a stand-in drifts silently; one table with" );
	puts( "# two independent recomputations is what turns the drift into a failure." );
	puts( "# Hand-editing a row makes both suites wrong at once, which is exactly" );
	puts( "# what generating it prevents." );
	puts( "#" );
	puts( "# S <input> <atoi> <atof> <bool> <vx> <vy> <vz> <r> <g> <b> <a> <%i> <%g> <[%g %g %g]> <%d %d %d %d>" );
	puts( "# F <value> <(int)> <!=0> <%g>" );

	for ( i = 0; i < sizeof( g_in ) / sizeof( g_in[0] ); i++ )
	{
		const char *s = g_in[i];

		int asInt = atoi( s ); /* STRING -> INTEGER */
		float asFloat = (float)atof( s ); /* STRING -> FLOAT   */
		int asBool = atoi( s ) != 0; /* STRING -> BOOLEAN (atoi!) */

		float v[3] = { 0, 0, 0 }; /* STRING -> VECTOR */
		if ( sscanf( s, "[%f %f %f]", &v[0], &v[1], &v[2] ) == 0 )
			sscanf( s, "%f %f %f", &v[0], &v[1], &v[2] );

		int nRed = 0, nGreen = 0, nBlue = 0, nAlpha = 255; /* STRING -> COLOR32 */
		sscanf( s, "%d %d %d %d", &nRed, &nGreen, &nBlue, &nAlpha );

		char bInt[512], bFlt[512], bVec[512], bCol[512];
		snprintf( bInt, sizeof bInt, "%i", asInt );
		snprintf( bFlt, sizeof bFlt, "%g", asFloat );
		snprintf( bVec, sizeof bVec, "[%g %g %g]", (double)v[0], (double)v[1], (double)v[2] );
		snprintf( bCol, sizeof bCol, "%d %d %d %d", (int)(unsigned char)nRed, (int)(unsigned char)nGreen,
				  (int)(unsigned char)nBlue, (int)(unsigned char)nAlpha );

		fputs( "S\t", stdout );
		quoted( s );
		printf( "\t%d\t", asInt );
		exact( asFloat );
		printf( "\t%d\t", asBool );
		exact( v[0] );
		putchar( '\t' );
		exact( v[1] );
		putchar( '\t' );
		exact( v[2] );
		printf( "\t%u\t%u\t%u\t%u\t%s\t%s\t%s\t%s\n", (unsigned char)nRed, (unsigned char)nGreen, (unsigned char)nBlue,
				(unsigned char)nAlpha, bInt, bFlt, bVec, bCol );
	}

	{
		/* FIELD_FLOAT -> FIELD_INTEGER and -> FIELD_BOOLEAN, and ToString's %g
           across every bracket it switches format on. The out-of-range int is
           undefined in C and is cvttss2si's INT_MIN on this machine. */
		static const float fv[] = {
			0.0f,  -0.0f,  1.0f,      -1.0f,     5.7f,       -5.7f,      0.5f,        -0.5f,       0.1f,          1e-5f,
			1e-4f, 100.0f, 123456.0f, 999999.0f, 1000000.0f, 1234567.0f, 12345.6789f, 16777216.0f, 2147483520.0f, 3e9f,
			-3e9f, 1e30f,  -1e30f,    1e-30f,    1.5f,       -2.5f,      3.25f,       0.000123456f };
		for ( i = 0; i < sizeof fv / sizeof fv[0]; i++ )
		{
			char b[64];
			snprintf( b, sizeof b, "%g", fv[i] );
			fputs( "F\t", stdout );
			exact( fv[i] );
			printf( "\t%d\t%d\t%s\n", (int)fv[i], fv[i] != 0, b );
		}
	}

	return 0;
}
