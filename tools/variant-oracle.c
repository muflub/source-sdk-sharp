/*  variant-oracle -- what stock's variant_t actually answers, from libc.
 *
 *  WHY THIS FILE EXISTS. plan_entity.md moves variant_t::Convert into managed
 *  code (SourceSharp.Abi/VariantValue.cs). A conversion that silently answers a
 *  WRONG value looks exactly like a map author's mistake and there is no crash
 *  to find it by, so the managed table had to be pinned against what stock does
 *  rather than against what the C# type system finds natural -- the two
 *  disagree about empty strings, malformed numbers, hex, and values that do not
 *  fit.
 *
 *  Every expression below is COPIED VERBATIM out of variant_t::Convert and
 *  variant_t::ToString (src/game/server/cbase.cpp). Build and run it, and the
 *  output is the expected column of:
 *
 *      src/test/managed/VariantParseTests.cs
 *      src/sourcesharp/test/variant_convert_test.cpp
 *
 *  Both of those assert the same table, one in each language, because
 *  VariantParse is a stand-in for native code and a stand-in drifts silently.
 *
 *  RUN IT IN THE SNIPER CONTAINER, NEVER ON THE HOST. The two glibcs disagree
 *  about sscanf("1e", "%f") -- 2.31 in the container assigns 1, a modern host
 *  one assigns nothing -- and the game and src/buildcpptests both build in the
 *  container, so the container is the authority. A host-generated table makes
 *  the vector column wrong for every truncated exponent, which is how this
 *  paragraph came to be written. The regeneration command is in the file's own
 *  header comment.
 *
 *  It is not built by anything. It is a way of ASKING the runtime a question,
 *  kept so the answer can be asked again rather than remembered.
 */
