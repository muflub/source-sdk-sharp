namespace SourceSharp.MapGen;

/// <summary>
/// The AI's purpose-built test maps (plan_hl2mp_ai §6.6), as room libraries
/// for map-tools' rooms pipeline (`ssmap room` then `ssmap link`, which
/// writes the level's `.nav3d`): each room a 512-unit cell with a 16-unit
/// shell and 128 x 480 doors plugged with the compile trigger, rooms in a row
/// joined east to west (a door stands on the floor only at the full height, cell - 2 x wall). Our own fixtures, so `ss_` names; the entities inside
/// are stock classes.
/// </summary>
public static class AiTestMaps
{
    public const float Cell = 512f;
    public const float Wall = 16f;
    public const float DoorWidth = 128f;
    public const float DoorHeight = 480f;
    public const float Gap = 256f;

    private const string Floor = "DEV/DEV_MEASUREGENERIC01B";
    private const string Shell = "DEV/DEV_MEASUREWALL01A";
    private const string Plug = "TOOLS/TOOLSTRIGGER";
    private const string Ledge = "DEV/DEV_MEASUREGENERIC01";

    /// <summary>A level of the rooms in a row, west to east.</summary>
    public static string Level(string library, IReadOnlyList<string> rooms)
        => $"# {library}: generated by src/mapgen (AiTestMaps); `make map MAP=<name>` links it\n"
           + $"library: {library}\nrows: 1\ncolumns: {rooms.Count}\ngrid:\n  - [{string.Join(", ", rooms)}]\n";

    /// <summary>
    /// ss_ai_nav: the spawn and a step up to a platform; a 32 u and a 48 u
    /// ledge, a 40 u crawlspace to a nook, a hurt strip; a ladder to a 160 u
    /// platform with a drop off it, and a door in a partition. A pickup on
    /// each, so a bot sent to each pickup in turn crosses every edge type.
    /// </summary>
    public static VmfMap Nav()
    {
        var map = new VmfMap();
        map.World.Add(new("skyname", "sky_day01_01"));

        // spawn: the spawn, a health kit, four 16 u steps to a 64 u platform with a shotgun.
        Room(map, 1, "spawn", east: true, west: true);
        Point o = Origin(1);
        // Four spawns, so a human and bots do not stand in one another.
        foreach (float y in (float[])[192, 256, 320, 384])
            Spawn(map, o + new Point(96, y, 16));
        Item(map, "item_healthkit", o + new Point(160, 256, 24));
        for (int s = 1; s <= 4; s++)
            map.WorldSolids.Add(VmfMap.Box(o + new Point(256 + (s - 1) * 32, 32, 16), o + new Point(496, 160, 16 + s * 16), Ledge));
        Item(map, "weapon_shotgun", o + new Point(456, 96, 96));

        // ledges: a 32 u ledge (a jump) with an SMG, a 48 u ledge (a crouch jump)
        // with a 357, a crawlspace 40 u high to a nook with a battery, a hurt strip.
        Room(map, 2, "ledges", east: false, west: true);
        o = Origin(2);
        // A wall from the north shell between them, so neither ledge is reached from the other.
        map.WorldSolids.Add(VmfMap.Box(o + new Point(64, 352, 16), o + new Point(224, 496, 48), Ledge));
        Item(map, "weapon_smg1", o + new Point(144, 440, 64));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(224, 336, 16), o + new Point(288, 496, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(288, 352, 16), o + new Point(448, 496, 64), Ledge));
        Item(map, "weapon_357", o + new Point(368, 440, 80));
        // The crawl: a 40 u gap under a slab, walled both sides, to a nook.
        // Its slab runs from the west wall to a block at x 256, so the nook under
        // it opens only northward, along y 128.
        map.WorldSolids.Add(VmfMap.Box(o + new Point(16, 16, 56), o + new Point(256, 128, 496), Ledge));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 16, 16), o + new Point(272, 128, 496), Ledge));
        Item(map, "item_battery", o + new Point(136, 48, 24));
        var hurt = new VmfEntity { ClassName = "trigger_hurt" };
        hurt.Set("damage", "20").Set("damagetype", "0").Set("spawnflags", "1");
        hurt.Solids.Add(VmfMap.Box(o + new Point(352, 160, 16), o + new Point(416, 224, 48), "TOOLS/TOOLSTRIGGER"));
        map.Entities.Add(hurt);

        // climb: a ladder up a 160 u platform's face to a crossbow, a drop off
        // its far edge, and a partition with a door between them and the east door, an AR2 behind it.
        Room(map, 0, "climb", east: true, west: false);
        o = Origin(0);
        map.WorldSolids.Add(VmfMap.Box(o + new Point(160, 288, 16), o + new Point(352, 496, 176), Ledge));
        Item(map, "weapon_crossbow", o + new Point(256, 440, 192));
        var ladder = new VmfEntity { ClassName = "func_useableladder" };
        // point0 and point1 stay as written through map-tools' room split, its
        // room compile and its link (only origins move; plan_hl2mp_ai §12.4),
        // so this room is first in the library and in the level, unturned,
        // where its library, room and level coordinates are one.
        Point placed = new(0, 0, 0);
        ladder.Set("origin", (o + new Point(256, 270, 16)).ToString()).Set("point0", (placed + new Point(256, 270, 16)).ToString())
              .Set("point1", (placed + new Point(256, 270, 176)).ToString()).Set("StartDisabled", "0").Set("ladderSurfaceProperties", "ladder");
        map.Entities.Add(ladder);
        var top = new VmfEntity { ClassName = "info_ladder_dismount" };
        top.Set("origin", (o + new Point(256, 320, 184)).ToString());
        map.Entities.Add(top);
        // The partition at x 400..416 across the room, its 64 u door.
        map.WorldSolids.Add(VmfMap.Box(o + new Point(400, 16, 16), o + new Point(416, 96, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(400, 160, 16), o + new Point(416, 496, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(400, 96, 128), o + new Point(416, 160, 496), Shell));
        var door = new VmfEntity { ClassName = "func_door" };
        door.Set("targetname", "ai_door").Set("movedir", "-90 0 0").Set("speed", "100").Set("wait", "3").Set("lip", "8")
            .Set("spawnflags", "1024");
        // No origin key: with one, map-tools' room navigation places the
        // door's obstacle box about the map origin (its model's own bounds),
        // not where the door stands (plan_hl2mp_ai §12.4).
        door.Solids.Add(VmfMap.Box(o + new Point(402, 96, 16), o + new Point(414, 160, 128), Shell));
        map.Entities.Add(door);
        Item(map, "weapon_ar2", o + new Point(376, 128, 24));
        return map;
    }

    /// <summary>
    /// ss_ai_sight: one long hall split by a wall with a window cut in it, a
    /// half-cover block (40 u, under a standing eye), a func_door in a second
    /// wall, and a stack of two crates: the occluders §6.6 scripts a target
    /// past, for the sight table now and the sight events of Phase 4.
    /// </summary>
    public static VmfMap Sight()
    {
        var map = new VmfMap();
        map.World.Add(new("skyname", "sky_day01_01"));
        Room(map, 0, "watch", east: true, west: false);
        Point o = Origin(0);
        Spawn(map, o + new Point(64, 256, 16));
        // The window wall at x 256..272: solid but for a 64 x 48 window at eye height.
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 16, 16), o + new Point(272, 192, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 256, 16), o + new Point(272, 496, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 192, 16), o + new Point(272, 256, 56), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 192, 104), o + new Point(272, 256, 496), Shell));
        // Half cover: a 40 u block in the open, east of the wall.
        map.WorldSolids.Add(VmfMap.Box(o + new Point(352, 384, 16), o + new Point(416, 448, 56), Ledge));

        Room(map, 1, "doors", east: false, west: true);
        o = Origin(1);
        // A wall at x 256..272 with a door in it, and two crates stacked beside.
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 16, 16), o + new Point(272, 224, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 288, 16), o + new Point(272, 496, 496), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(256, 224, 144), o + new Point(272, 288, 496), Shell));
        var door = new VmfEntity { ClassName = "func_door" };
        door.Set("targetname", "sight_door").Set("movedir", "-90 0 0").Set("speed", "100").Set("wait", "-1").Set("lip", "8").Set("spawnflags", "0");
        door.Solids.Add(VmfMap.Box(o + new Point(258, 224, 16), o + new Point(270, 288, 144), Shell));
        map.Entities.Add(door);
        for (int k = 0; k < 2; k++)
        {
            var crate = new VmfEntity { ClassName = "prop_physics" };
            crate.Set("model", "models/props_junk/wood_crate001a.mdl").Set("targetname", $"sight_crate_{k}")
                 .Set("origin", (o + new Point(128, 400, 36 + 40 * k)).ToString()).Set("spawnflags", "8");
            map.Entities.Add(crate);
        }

        return map;
    }

    /// <summary>
    /// ss_ai_hearing (plan_hl2mp_ai §6.6): three rooms in a row, each behind
    /// the next one's walls ("near", "middle", "far"), joined by their
    /// doorways; four spawns in the near room; a 357, a shotgun and an SMG1
    /// on the near room's floor and the far room's, for a scripted target to
    /// pick up and fire or reload at scripted distances from a listener.
    /// </summary>
    public static VmfMap Hearing()
    {
        var map = new VmfMap();
        map.World.Add(new("skyname", "sky_day01_01"));
        string[] names = ["near", "middle", "far"];
        for (int i = 0; i < names.Length; i++)
        {
            Room(map, i, names[i], east: i < names.Length - 1, west: i > 0);
            // A partition across the room's middle, open only by its doorway's line, so walls stand between rooms and inside them.
            Point o = Origin(i);
            map.WorldSolids.Add(VmfMap.Box(o + new Point(320, 16, 16), o + new Point(336, 160, 496), Shell));
            map.WorldSolids.Add(VmfMap.Box(o + new Point(320, 352, 16), o + new Point(336, 496, 496), Shell));
        }

        Point near = Origin(0), far = Origin(2);
        foreach (float y in (float[])[96, 192, 320, 416])
            Spawn(map, near + new Point(64, y, 16));
        Item(map, "weapon_357", near + new Point(256, 96, 24));
        Item(map, "weapon_shotgun", near + new Point(256, 416, 24));
        Item(map, "weapon_357", far + new Point(400, 256, 24));
        Item(map, "weapon_smg1", far + new Point(400, 416, 24));
        return map;
    }

    /// <summary>
    /// ss_ai_duel (plan_hl2mp_ai §6.6, Phase 5 step 6): one open room for a
    /// close duel over reload windows, push, hold and retreat; a crate at its
    /// middle's side for cover, a health kit at each end, SMG1 ammo.
    /// </summary>
    public static VmfMap Duel()
    {
        var map = new VmfMap();
        map.World.Add(new("skyname", "sky_day01_01"));
        Room(map, 0, "arena", east: false, west: false);
        Point o = Origin(0);
        foreach (float y in (float[])[128, 384])
        {
            Spawn(map, o + new Point(64, y, 16));
            Spawn(map, o + new Point(448, y, 16));
        }

        map.WorldSolids.Add(VmfMap.Box(o + new Point(224, 400, 16), o + new Point(288, 464, 80), Ledge));
        Item(map, "item_healthkit", o + new Point(40, 256, 24));
        Item(map, "item_healthkit", o + new Point(472, 256, 24));
        Item(map, "item_ammo_smg1", o + new Point(256, 64, 24));
        return map;
    }

    /// <summary>
    /// ss_ai_routes (§6.6, Phase 5 step 6): three rooms in a row, each split
    /// by a partition open only at its doorway's line, for memory, prediction
    /// and Headhunter: who is where cannot be seen from the next room.
    /// </summary>
    public static VmfMap Routes()
    {
        var map = new VmfMap();
        map.World.Add(new("skyname", "sky_day01_01"));
        string[] names = ["west", "middle", "east"];
        for (int i = 0; i < names.Length; i++)
        {
            Room(map, i, names[i], east: i < names.Length - 1, west: i > 0);
            Point o = Origin(i);
            map.WorldSolids.Add(VmfMap.Box(o + new Point(320, 16, 16), o + new Point(336, 160, 496), Shell));
            map.WorldSolids.Add(VmfMap.Box(o + new Point(320, 352, 16), o + new Point(336, 496, 496), Shell));
            foreach (float y in (float[])[96, 416])
                Spawn(map, o + new Point(64, y, 16));
        }

        Item(map, "item_healthkit", Origin(1) + new Point(160, 256, 24));
        Item(map, "weapon_ar2", Origin(2) + new Point(400, 256, 24));
        return map;
    }

    /// <summary>The cell's low corner of the room at index <paramref name="i"/>.</summary>
    public static Point Origin(int i) => new(i * (Cell + Gap), 0, 0);

    private static void Room(VmfMap map, int index, string name, bool east, bool west)
    {
        Point o = Origin(index);
        float c = Cell, w = Wall;
        map.WorldSolids.Add(VmfMap.Box(o, o + new Point(c, c, w), Floor));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(0, 0, c - w), o + new Point(c, c, c), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(0, 0, w), o + new Point(c, w, c - w), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(0, c - w, w), o + new Point(c, c, c - w), Shell));
        WallX(map, o, 0f, west);
        WallX(map, o, c - w, east);

        var room = new VmfEntity { ClassName = "info_room" };
        room.Set("origin", o.ToString()).Set("name", name).Set("cell_size", $"{(int)c}").Set("door_width", $"{(int)DoorWidth}")
            .Set("door_height", $"{(int)DoorHeight}").Set("wall_depth", $"{(int)w}");
        map.Entities.Add(room);
        var light = new VmfEntity { ClassName = "light" };
        light.Set("origin", (o + new Point(c / 2, c / 2, c - 64)).ToString()).Set("_light", "255 250 235 400");
        map.Entities.Add(light);
    }

    /// <summary>The wall at x = <paramref name="x"/> (cell-local), with a plugged door when it has one.</summary>
    private static void WallX(VmfMap map, Point o, float x, bool door)
    {
        float c = Cell, w = Wall, y0 = (c - DoorWidth) / 2, y1 = y0 + DoorWidth, z1 = w + DoorHeight;
        if (!door)
        {
            map.WorldSolids.Add(VmfMap.Box(o + new Point(x, w, w), o + new Point(x + w, c - w, c - w), Shell));
            return;
        }

        map.WorldSolids.Add(VmfMap.Box(o + new Point(x, w, w), o + new Point(x + w, y0, c - w), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(x, y1, w), o + new Point(x + w, c - w, c - w), Shell));
        if (z1 < c - w)
            map.WorldSolids.Add(VmfMap.Box(o + new Point(x, y0, z1), o + new Point(x + w, y1, c - w), Shell));
        map.WorldSolids.Add(VmfMap.Box(o + new Point(x, y0, w), o + new Point(x + w, y1, z1), Plug));
    }

    private static void Spawn(VmfMap map, Point at)
    {
        var e = new VmfEntity { ClassName = "info_player_deathmatch" };
        e.Set("origin", at.ToString()).Set("angles", "0 0 0");
        map.Entities.Add(e);
    }

    private static void Item(VmfMap map, string className, Point at)
    {
        var e = new VmfEntity { ClassName = className };
        e.Set("origin", at.ToString());
        map.Entities.Add(e);
    }
}
