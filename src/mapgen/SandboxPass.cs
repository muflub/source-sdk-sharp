using System.Reflection;
using System.Text.Json;
using SourceSharp.Shared;

namespace SourceSharp.MapGen;

/// <summary>
/// Part 6's Phase 4 gate: ONE batch pass over the sandbox map, after the ports
/// have landed.
///
/// The gate is deliberately not "check each entity as it is ported". A port that
/// is verified alone is verified in a map with nothing else in it; the failure
/// this gate exists to catch is the one that only appears when all of them are
/// loaded at once — a factory that never registered, a Spawn() that throws and
/// is swallowed, a classname the shim knows and the server does not. Every one
/// of those removes the entity SILENTLY: the map still loads, the station is
/// still there, and the only evidence is that nothing stands on the pad.
///
/// So the measurement is: what the map DECLARES (the BSP's entity lump, as
/// <c>debug-api mapents</c> reports it) against what the server actually HAS
/// (<c>debug-api ents &lt;class&gt;</c>, per classname). A classname with fewer
/// live entities than declared is the defect, and the whole map is measured in
/// one pass.
///
/// <para>
/// THE EXCUSES ARE DERIVED, NOT LISTED. Three kinds of entity are legitimately
/// absent at runtime, and a hand-kept list of them is exactly how a real
/// regression gets absorbed into the excuse column. So each is computed from the
/// map itself:
/// </para>
/// <list type="bullet">
/// <item><description><c>light</c> and <c>info_null</c> — the compiler bakes the
/// first into the lightmaps and deletes the second; neither has ever existed at
/// runtime, in this mod or in stock Source.</description></item>
/// <item><description>a <c>point_template</c>'s templates — named by that
/// entity's own <c>TemplateNN</c> keyvalues, which this class READS rather than
/// assumes. A template is taken out of the world at level start by design; that
/// is what makes it a template. Scoped by exact targetname, so a fourth missing
/// entity of the same class is still a failure.</description></item>
/// <item><description><c>worldspawn</c> — entity 0, which no class query
/// enumerates.</description></item>
/// </list>
/// </summary>
public static class SandboxPass
{
    /// <summary>One entity as the map's entity lump declares it.</summary>
    public sealed record DeclaredEntity(
        string ClassName,
        string TargetName,
        IReadOnlyDictionary<string, string> KeyValues);

    /// <summary>
    /// A class the mod registers that the map does not contain, and why — or
    /// why not.
    /// </summary>
    /// <param name="Exemption">
    /// Null when nothing excuses the absence, which is the failing case. A
    /// non-null exemption names the reason, so a reader can disagree with it.
    /// </param>
    public sealed record Absence(string ClassName, string? Exemption)
    {
        public bool Fails => Exemption is null;
    }

    /// <summary>A classname the server is short of, and why — or why not.</summary>
    /// <param name="Excuse">
    /// Null when nothing excuses the shortfall, which is the failing case. A
    /// non-null excuse names the mechanism, so a reader can disagree with it.
    /// </param>
    public sealed record Shortfall(string ClassName, int Declared, int Live, int Excused, string? Excuse)
    {
        public bool Fails => Excuse is null || Live + Excused < Declared;
    }

    /// <summary>
    /// The two classnames the map compiler removes before the server ever sees
    /// the map. Not a courtesy to this port — stock Source does the same.
    /// </summary>
    public static bool RemovedByCompiler(string className)
        => className is "light" or "info_null";

