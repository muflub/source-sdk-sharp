    // crash shipped. Two checks existed and neither joined up:
    //
    //   SandboxTests.Coverage   registered classes ⊆ what Sandbox.Build() emits
    //   SandboxPass.Audit       what the BSP declares ⊆ what the server has
    //
    // Between them sits vbsp, and nothing checked across it. The .vmf is
    // regenerated by `make sandbox` and the .bsp only by `make map`, which needs
    // Wine, a Steam depot and the HL2 content — so the .bsp routinely lags the
    // generator by weeks, and BOTH checks stay green while it does. When this
