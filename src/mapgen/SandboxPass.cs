    /// <summary>
    /// Every classname the mod implements, read from the <c>[ScriptedEntity]</c>
    /// attributes on the server assembly.
    ///
    /// Read rather than listed, so adding an entity to the mod extends the thing
    /// the map is measured against and forgetting to demonstrate it FAILS.
    /// </summary>
    /// <remarks>
    /// Read through <see cref="CustomAttributeData"/> and matched by the
    /// attribute's NAME rather than by referencing
    /// <c>ScriptedEntityAttribute</c> itself, and that is deliberate rather than
    /// squeamish. Discovery scans every loaded assembly that references
    /// <c>SourceSharp.Abi</c>, on the reasoning that an assembly with no ABI
    /// reference cannot be carrying a declaration — so naming an ABI type here
    /// would quietly enrol this build tool as a mod assembly.
    /// <c>LoadedAssemblyTests</c> pins that, and caught exactly this.
    /// </remarks>
    public static IReadOnlyList<string> Registered()
        => typeof(SourceSharp.Server.ServerModule).Assembly
            .GetTypes()
            .SelectMany(t => t.GetCustomAttributesData())
            .Where(d => d.AttributeType.Name == "ScriptedEntityAttribute"
                     && d.ConstructorArguments.Count > 0)
            .Select(d => d.ConstructorArguments[0].Value as string ?? "")
            .Where(c => c.Length > 0)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(c => c, StringComparer.Ordinal)
            .ToList();

    //-------------------------------------------------------------------------
    // THE TEMP ENTITY LEG.
    //
    // The coverage rule above compares CLASSNAMES, and a temp entity has none.
    // It is a message: no factory, no edict, nothing in the entity lump and
    // nothing `debug-api ents` can be asked about. So the forty-three the port
    // landed were invisible to every check in this file -- the map could contain
    // an example of all 274 registered entities and demonstrate not one effect.
    //
    // ss_te_tester (plan 9.1) is the classname that stands for all of them, and
    // that is exactly what makes the plain rule useless here: ONE ss_te_tester
    // anywhere satisfies "the map contains this classname", and forty-two
    // missing effects pass. So this leg reads the `te` KEYVALUE out of each one
    // instead. BspEntities.Read already returns every entity's full keyvalue
    // dictionary, so it is a filter over existing output rather than new
    // parsing.
    //
    // THERE IS NO EXEMPTION LIST AND THERE IS NOT MEANT TO BE (plan 9.2).
    // Exemptions excuse entities a mapper cannot place or that vbsp eats;
    // neither can apply, because firing IS the whole of what a temp entity does.
    // A temp entity that cannot be fired from a station has already failed the
    // port. The one class this rule does not ask about is derived from the
    // declaration rather than excused by name -- see Registered TempEnts.
    //-------------------------------------------------------------------------

    /// <summary>The classname one temp entity tester carries.</summary>
    public const string TeTesterClass = "ss_te_tester";

    /// <summary>The keyvalue on it that names which temp entity it fires.</summary>
    public const string TeTesterKey = "te";

    /// <summary>
    /// Every temp entity this build can send, read from the
    /// <c>[TempEntity]</c> declarations in the shared assembly.
    ///
    /// <para>
    /// <c>RegistersClass = false</c> IS THE ONLY THING LEFT OUT, and it is not
    /// an exemption: such a declaration is a TABLE for others to nest and claims
    /// no ServerClass of its own, so it has no handle and native has nothing to
    /// play. <c>CBaseTempEntity</c> is one (stock still registers that name, and
    /// a second would hang the join — plan 2E) and its blob is zero bytes, which
    /// <c>Engine.TempEntPlayback</c> refuses outright; <c>CEffectData</c> is the
    /// other and is a nested payload rather than a temp entity at all. When
    /// <c>basetempentity.cpp</c> is finally evicted and that flag flips, this
    /// rule will start asking for a tester for it — which is right, because it
    /// will by then be a thing that can be sent.
    /// </para>
    /// </summary>
    /// <remarks>
    /// Read through <see cref="CustomAttributeData"/> and matched by the
    /// attribute's NAME, for the same reason <see cref="Registered"/> is: naming
    /// an ABI type here would enrol this build tool as a mod assembly.
    /// </remarks>
    public static IReadOnlyList<string> RegisteredTempEnts()
        => typeof(SourceSharp.Shared.EntityNames).Assembly
            .GetTypes()
            .SelectMany(t => t.GetCustomAttributesData().Select(d => (Type: t, Data: d)))
            .Where(p => p.Data.AttributeType.Name == "TempEntityAttribute" && ClaimsAClass(p.Data))
            .Select(p => ClassNameOf(p.Type, p.Data))
            .Where(c => c.Length > 0)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(c => c, StringComparer.Ordinal)
            .ToList();

    /// <summary>
    /// The wire class name a declaration claims: the first constructor argument
    /// if it gave one, and otherwise <c>CTE</c> + the class name without its
    /// <c>Te</c>.
    ///
    /// <para>
    /// A SECOND COPY OF A RULE THAT LIVES IN <c>TempEntityAttribute</c>, and
    /// deliberately so: see this class's remarks. Naming the ABI type here would
    /// enrol this build tool as a mod assembly, so the name is derived from
    /// <see cref="CustomAttributeData"/> and the type instead.
    /// </para>
    ///
    /// <para>
    /// A SECOND COPY IS A THING THAT DRIFTS, so it is gated:
    /// <c>SandboxTeTests</c> asserts this list against the names the REGISTRY
    /// built, which is the other copy. The two disagreeing is a red test rather
    /// than a sandbox that quietly stops covering half the inventory — which is
    /// what happened the day the declarations stopped spelling their names out
    /// and this method silently returned nothing.
    /// </para>
    /// </summary>
    private static string ClassNameOf(Type type, CustomAttributeData attribute)
    {
        if (attribute.ConstructorArguments.Count > 0
            && attribute.ConstructorArguments[0].Value is string named
            && named.Length > 0)
        {
            return named;
        }

        return type.Name.StartsWith("Te", StringComparison.Ordinal) && type.Name.Length > 2
                   ? "CTE" + type.Name[2..]
                   : "";
    }

    /// <summary>
    /// Whether a <c>[TempEntity]</c> claims a ServerClass, which is the named
    /// property <c>RegistersClass</c> defaulting to true.
    /// </summary>
    private static bool ClaimsAClass(CustomAttributeData attribute)
    {
        foreach (var argument in attribute.NamedArguments)
        {
            if (argument.MemberName == "RegistersClass")
                return argument.TypedValue.Value is bool claims && claims;
        }

        return true;
    }

    /// <summary>
    /// Which temp entities a map demonstrates: the <c>te</c> keyvalue of every
    /// <c>ss_te_tester</c> in it.
    /// </summary>
    public static HashSet<string> DemonstratedTempEnts(IEnumerable<DeclaredEntity> declared)
    {
        var fired = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var entity in declared)
        {
            if (!string.Equals(entity.ClassName, TeTesterClass, StringComparison.OrdinalIgnoreCase))
                continue;

            if (entity.KeyValues.TryGetValue(TeTesterKey, out string? te) && te.Length > 0)
                fired.Add(te);
        }

        return fired;
    }

    /// <summary>
    /// Every temp entity the build can send that the map fires from no
    /// <c>ss_te_tester</c>.
    ///
    /// <para>
    /// Shaped as <see cref="Absence"/> so it prints and fails through the same
    /// machinery the classname leg does — and every one of them has a null
    /// exemption, because there is no list one could come from.
    /// </para>
    /// </summary>
    public static List<Absence> AuditTempEntCoverage(
        IEnumerable<string> registered,
        IEnumerable<DeclaredEntity> declared)
    {
        var fired = DemonstratedTempEnts(declared);

        return registered.Distinct(StringComparer.OrdinalIgnoreCase)
                         .Where(c => !fired.Contains(c))
                         .OrderBy(c => c, StringComparer.Ordinal)
                         .Select(c => new Absence(c, null))
                         .ToList();
    }

    /// <summary>
    /// Every registered class with no instance in the map, each with its
    /// exemption or without one.
    ///
    /// <para>
    /// The rule is ONE INSTANCE, not a count: a class the map contains twice and
    /// the server has once is <see cref="Audit"/>'s business, not this one. This
    /// leg answers only "is there an example of this at all in the map the gate
    /// loads", which is the question that was never asked.
    /// </para>
    /// </summary>
    public static List<Absence> AuditCoverage(
        IEnumerable<string> registered,
        IEnumerable<DeclaredEntity> declared)
    {
        var present = declared
            .Select(e => e.ClassName)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        var absences = new List<Absence>();

        foreach (string className in registered.Distinct(StringComparer.OrdinalIgnoreCase)
                                               .OrderBy(c => c, StringComparer.Ordinal))
        {
            if (present.Contains(className))
                continue;

            Exemptions.TryGetValue(className, out string? reason);
            absences.Add(new Absence(className, reason));
        }

        return absences;
    }

    /// <summary>
    /// The targetnames a <c>point_template</c> in this map claims as templates.
    ///
    /// Read from the template entity's own keyvalues (<c>Template01</c>..), so
    /// adding a template to the map extends this set and adding an entity that
    /// merely fails to spawn does not.
    /// </summary>
    public static HashSet<string> TemplateTargets(IEnumerable<DeclaredEntity> declared)
    {
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var entity in declared)
        {
            if (!string.Equals(entity.ClassName, "point_template", StringComparison.OrdinalIgnoreCase))
                continue;

            foreach (var pair in entity.KeyValues)
            {
                if (pair.Key.StartsWith("Template", StringComparison.OrdinalIgnoreCase)
                    && pair.Value.Length > 0)
                {
                    names.Add(pair.Value);
                }
            }
        }

        return names;
    }

    /// <summary>
    /// The pass itself. Every classname the map declares, against the live count
    /// the server answered for it.
    /// </summary>
    /// <param name="live">
    /// Classname to live count. A classname absent from this map is treated as
    /// zero — an unasked question and an empty answer are the same failure here,
    /// and pretending otherwise would let a broken query read as a pass.
    /// </param>
    public static List<Shortfall> Audit(
        IEnumerable<DeclaredEntity> declared,
        IReadOnlyDictionary<string, int> live)
    {
        var entities = declared.ToList();
        var templates = TemplateTargets(entities);

        var declaredCounts = new Dictionary<string, int>(StringComparer.Ordinal);
        var excusedCounts = new Dictionary<string, int>(StringComparer.Ordinal);

        foreach (var entity in entities)
        {
            declaredCounts.TryGetValue(entity.ClassName, out int count);
            declaredCounts[entity.ClassName] = count + 1;

            if (templates.Contains(entity.TargetName))
            {
                excusedCounts.TryGetValue(entity.ClassName, out int excused);
                excusedCounts[entity.ClassName] = excused + 1;
            }
        }

        var shortfalls = new List<Shortfall>();

        foreach (var pair in declaredCounts.OrderBy(p => p.Key, StringComparer.Ordinal))
        {
            string className = pair.Key;
            int want = pair.Value;

            if (string.Equals(className, "worldspawn", StringComparison.Ordinal))
                continue;

            live.TryGetValue(className, out int have);
            excusedCounts.TryGetValue(className, out int excused);

            if (have >= want)
                continue;

            string? excuse = null;

            if (RemovedByCompiler(className))
            {
                excuse = "removed by the map compiler";
                excused = want;
            }
            else if (excused > 0)
            {
                excuse = $"{excused} taken as point_template template(s)";
            }

            shortfalls.Add(new Shortfall(className, want, have, excused, excuse));
        }

        return shortfalls;
    }

    /// <summary>
    /// Parses the entity list <c>debug-api mapents</c> answers with.
    /// </summary>
    public static List<DeclaredEntity> ReadMapEntities(string json)
    {
        var entities = new List<DeclaredEntity>();

        using var document = JsonDocument.Parse(json);

        if (!document.RootElement.TryGetProperty("entities", out var array))
            return entities;

        foreach (var element in array.EnumerateArray())
        {
            string className = element.TryGetProperty("classname", out var c) ? c.GetString() ?? "" : "";
            string targetName = element.TryGetProperty("targetname", out var t) ? t.GetString() ?? "" : "";

            var keyValues = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

            if (element.TryGetProperty("keyvalues", out var pairs))
            {
                foreach (var pair in pairs.EnumerateArray())
                {
                    string key = pair.TryGetProperty("key", out var k) ? k.GetString() ?? "" : "";
                    string value = pair.TryGetProperty("value", out var v) ? v.GetString() ?? "" : "";

                    if (key.Length > 0)
                        keyValues[key] = value;
                }
            }

            if (className.Length > 0)
                entities.Add(new DeclaredEntity(className, targetName, keyValues));
        }

        return entities;
    }

