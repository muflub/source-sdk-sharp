    /// <c>{"class":"...","count":N}</c>, concatenated.
    /// </summary>
    public static Dictionary<string, int> ReadLiveCounts(IEnumerable<string> lines)
    {
        var counts = new Dictionary<string, int>(StringComparer.Ordinal);

        foreach (string line in lines)
        {
            if (line.Trim().Length == 0)
                continue;

            using var document = JsonDocument.Parse(line);

            if (!document.RootElement.TryGetProperty("class", out var c))
                continue;

            string className = c.GetString() ?? "";
            int count = document.RootElement.TryGetProperty("count", out var n) ? n.GetInt32() : 0;

            if (className.Length > 0)
                counts[className] = count;
        }

        return counts;
    }

    /// <summary>
    /// The pass as text, the way the driver prints it. Every shortfall is shown
    /// — the excused ones too, because an excuse nobody reads is a list nobody
    /// checks.
    /// </summary>
    /// <param name="tempEnts">
    /// The temp entity leg, or null when the caller did not ask for one. It is a
    /// separate list rather than more <paramref name="absences"/> because the
    /// two answer different questions about different things — a classname the
    /// map should contain, and a temp entity the map should FIRE — and merging
    /// them would print a temp entity's class name as if the map were short of
    /// an entity of that name.
    /// </param>
    public static IEnumerable<string> Report(
        IReadOnlyList<DeclaredEntity> declared,
        IReadOnlyDictionary<string, int> live,
        IReadOnlyList<Shortfall> shortfalls,
        IReadOnlyList<Absence> absences,
        IReadOnlyList<Absence>? tempEnts = null)
    {
        int classes = declared.Select(e => e.ClassName).Distinct(StringComparer.Ordinal).Count();

        yield return $"declared: {declared.Count} entities across {classes} classnames";
        yield return $"live:     {live.Values.Sum()} entities answered across {live.Count} queries";

        foreach (var shortfall in shortfalls)
        {
            string verdict = shortfall.Fails ? "FAIL" : "ok  ";
            string reason = shortfall.Excuse ?? "nothing accounts for this";

            yield return $"  {verdict} {shortfall.ClassName}: declared {shortfall.Declared}, "
                       + $"live {shortfall.Live} — {reason}";
        }

        // The coverage leg. Printed even when it is empty, because a leg that
        // says nothing when it passes and nothing when it never ran is the
        // failure this whole check was added for.
        int unexcused = absences.Count(a => a.Fails);

        yield return $"coverage: {unexcused} registered class(es) absent from the map with "
                   + $"no exemption, {absences.Count - unexcused} absent and exempt by name";

        foreach (var absence in absences)
        {
            string verdict = absence.Fails ? "FAIL" : "ok  ";
            string reason = absence.Exemption ?? "the mod registers this and the map contains none";

            yield return $"  {verdict} {absence.ClassName}: absent — {reason}";
        }

        // The temp entity leg. Printed whenever the caller collected one, pass or
        // fail, for the same reason the coverage leg above is.
        if (tempEnts is not null)
        {
            yield return $"tempents: {tempEnts.Count} temp entit(ies) the mod sends with no "
                       + $"{TeTesterClass} in the map firing them";

            foreach (var absence in tempEnts)
                yield return $"  FAIL {absence.ClassName}: no {TeTesterClass} in the map fires it";
        }

        int failing = shortfalls.Count(s => s.Fails) + absences.Count(a => a.Fails)
                    + (tempEnts?.Count ?? 0);

        yield return failing == 0
            ? "PASS — every entity the map declares is alive, and every class the mod registers is in the map"
            : $"FAIL — {failing} classname(s) with nothing to account for it";
    }

    //-------------------------------------------------------------------------
    // Staleness: the COMPILED map against the generator that produced it.
    //
    // Every other check here scores the generator, and the generator is not
    // what anyone runs. ss_sandbox.bsp is build output — not committed, and
    // rebuildable only with Wine, a Steam depot and the HL2 content — so the
    // file on disk is whatever the last person to own a working map toolchain
    // compiled, and it drifts behind Sandbox.cs silently. It sat 72 classnames
    // behind once. It is behind by one keyvalue right now: the effects
    // station's env_explosion carries spawnflags 0 where the generator says 2,
    // so the reset button on the shipped map destroys the entity the station
    // exists to demonstrate.
    //
    // The reasoning that left this gap is worth naming, because it reads as
    // sound: `make test` cannot COMPILE a .bsp, therefore `make test` cannot
    // check one. The second half does not follow. Producing a map needs the
    // toolchain; READING one needs sixty lines of BspEntities and a file that
    // is already sitting in game/mod_sharp/maps. So the check belongs here
    // after all.
    //-------------------------------------------------------------------------

    /// <summary>
    /// One way a compiled map disagrees with the generator that produced it.
    /// </summary>
    /// <param name="ClassName">The generator's entity.</param>
    /// <param name="TargetName">
    /// Its targetname, which is how it is matched to its compiled counterpart.
    /// </param>
    /// <param name="Key">
    /// The keyvalue that disagrees, or null when the entity is missing from the
    /// compiled map altogether.
    /// </param>
    public sealed record Drift(
        string ClassName,
        string TargetName,
        string? Key,
        string? Generated,
        string? Compiled)
    {
        public override string ToString()
            => Key is null
                ? $"{ClassName} \"{TargetName}\" is in the generator and not in the compiled map"
                : $"{ClassName} \"{TargetName}\" has {Key} \"{Compiled}\" compiled, "
                  + $"but the generator says \"{Generated}\"";
    }

    /// <summary>
    /// Keys never compared, because vbsp does not carry them through unchanged
    /// and a difference in one of them says nothing about staleness.
    ///
    /// <para>
    /// <c>origin</c> and <c>angles</c> are rewritten and reformatted by the
    /// compiler. <c>hammerid</c> is assigned by the .vmf writer and renumbers
    /// whenever anything is inserted above it. Deliberately short: every key
    /// exempted here is a key a stale map could drift in unseen, so the list is
    /// the cost of the check and not a convenience.
    /// </para>
    /// </summary>
    public static bool KeyIsCompilerOwned(string key)
        => key is "origin" or "angles" or "hammerid";

    /// <summary>
    /// The generator's own map in the shape a compiled map arrives in, so the
    /// two can be compared without either side knowing about the other.
    /// </summary>
    public static List<DeclaredEntity> FromGenerator(VmfMap map)
    {
        var entities = new List<DeclaredEntity>();

        foreach (var entity in map.Entities)
        {
            var keyValues = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

            // Last write wins, matching VmfEntity.Set and the .vmf writer.
            foreach (var pair in entity.KeyValues)
                keyValues[pair.Key] = pair.Value;

            entities.Add(new DeclaredEntity(entity.ClassName, entity.Name, keyValues));
        }

        return entities;
    }

    /// <summary>
    /// Where a compiled map disagrees with the generator: entities the
    /// generator places that the compiled map lacks, and keyvalues whose values
    /// differ.
    ///
    /// <para>
    /// Matched on classname plus targetname, which is what the sandbox actually
    /// keys on — every station entity is named because the reset buttons have
    /// to address them. Unnamed entities are skipped rather than guessed at: a
    /// positional match would report drift whenever anything moved, and a check
    /// that cries wolf gets muted, which is how the last one stopped working.
    /// </para>
    ///
    /// <para>
    /// One-directional on purpose. Entities in the compiled map that the
    /// generator does not place are not drift — vbsp synthesises its own, and
    /// worldspawn is never a generator entity.
    /// </para>
    /// </summary>
    public static List<Drift> Staleness(
        IEnumerable<DeclaredEntity> generated,
        IEnumerable<DeclaredEntity> compiled)
    {
        var byKey = new Dictionary<(string, string), List<DeclaredEntity>>();

        foreach (var entity in compiled)
        {
            var key = (entity.ClassName.ToLowerInvariant(), entity.TargetName.ToLowerInvariant());

            if (!byKey.TryGetValue(key, out var bucket))
                byKey[key] = bucket = [];

            bucket.Add(entity);
        }

        var drifts = new List<Drift>();

        foreach (var entity in generated)
        {
            if (entity.TargetName.Length == 0)
                continue;

            // The compiler deletes these before writing the lump, so their
            // absence is correct rather than stale.
            if (RemovedByCompiler(entity.ClassName))
                continue;

            var key = (entity.ClassName.ToLowerInvariant(), entity.TargetName.ToLowerInvariant());

            if (!byKey.TryGetValue(key, out var candidates) || candidates.Count == 0)
            {
                drifts.Add(new Drift(entity.ClassName, entity.TargetName, null, null, null));
                continue;
            }

            // With several entities sharing a name, one of them agreeing is
            // enough: which of the identical copies a reset button hits is not
            // a thing this check has an opinion about.
            var best = candidates
                .Select(candidate => Disagreements(entity, candidate))
                .OrderBy(list => list.Count)
                .First();

            drifts.AddRange(best);
        }

        return drifts;
    }

    /// <summary>
    /// The keys where one generator entity and one compiled entity disagree.
    /// </summary>
    private static List<Drift> Disagreements(DeclaredEntity generated, DeclaredEntity compiled)
    {
        var drifts = new List<Drift>();

        foreach (var pair in generated.KeyValues)
        {
            if (KeyIsCompilerOwned(pair.Key))
                continue;

            compiled.KeyValues.TryGetValue(pair.Key, out string? actual);

            if (!string.Equals(actual, pair.Value, StringComparison.Ordinal))
            {
                drifts.Add(new Drift(generated.ClassName, generated.TargetName,
                                     pair.Key, pair.Value, actual));
            }
        }

        return drifts;
    }
