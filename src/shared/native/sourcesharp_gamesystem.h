#pragma once

#ifdef CLIENT_DLL

// The client's half, in the server's shape. IManagedRuntimeEnvironment is what
// the shell provides; IClientRuntimeAdapter is what the loader hands back.
// GetGlobalVars() returns the CGlobalVarsBase the client is handed.
//
// On a listen server both DLLs call SourceSharp_Acquire, which refcounts one CLR
// in libsourcesharp.so. Each DLL loads once from its Init and unloads once from
// its Shutdown; a side must never release a runtime it did not load.

class CGlobalVarsBase;

class IManagedRuntimeEnvironment
{
protected:
    virtual ~IManagedRuntimeEnvironment() {};

public:
    virtual void *GetEngineInterface(const char *pName, int *pReturnCode) = 0;
    virtual CGlobalVarsBase &GetGlobalVars() = 0;
};

// The client's adapter. OnSystemStop runs the managed Shutdown slot, then
// UnloadSide and Release (the client's share of the refcounted CLR).
class IClientRuntimeAdapter
{
protected:
    virtual ~IClientRuntimeAdapter() {};

public:
    virtual void OnSystemStop() = 0;

    virtual void OnLevelInit( const char *pMapName ) = 0;
    virtual void OnLevelShutdown() = 0;

    virtual void OnFrame( float flFrameTime ) = 0;
};

IClientRuntimeAdapter *LoadManagedRuntime( IManagedRuntimeEnvironment *env );

// Null-safe, so a Shutdown after a failed Init needs no guard. The destructor is
// protected because the caller does not own the object.
void UnloadManagedRuntime( IClientRuntimeAdapter *pRuntime );

// Hands the adapter to CSourceSharpSystem, which forwards level and frame events.
// The row clears its copy in its Shutdown(), which runs before the shell releases
// the adapter.
void SourceSharp_SetClientRuntime( IClientRuntimeAdapter *pRuntime );

#else

#include "sourcesharp.h"

class CGlobalVars;

class IManagedRuntimeEnvironment
{
protected:
    virtual ~IManagedRuntimeEnvironment() {};

public:
    virtual void *GetEngineInterface(const char *pName, int *pReturnCode) = 0;
    virtual CGlobalVars &GetGlobalVars() = 0;

    // No Add() for server classes: they link themselves alphabetically and that
    // order is the wire format both sides rebuild class ids from.
};

class MapLoadInfo
{
public:
    const char *m_szName = {};
    const char *m_szEntities = {};
    const char *m_szOldName = {};
    const char *m_szLandMark = {};
};

// Implemented by managed and generated by tools/managed-areas: no virtual
// destructor (lifetime is Release, the last slot), blittable slots. Stopping is not a slot: DLLShutdown calls
// SourceSharp_UnloadManagedSide.
#include "imanaged_runtime.h"

IManagedRuntimeServer *LoadManagedRuntime(IManagedRuntimeEnvironment *env);

// This load's runtime, or NULL outside a load. Asked at each call, never kept:
// a reload acquires a new one.
IManagedRuntimeServer *ManagedRuntimeServer();

// Unloads the managed side; the runtime and the root are released first.
void SourceSharp_UnloadManagedSide();

// Services a cs_sv_reload request. Called at the top of GameFrame, so no other
// engine call can arrive while the managed side is unloaded.
void SourceSharp_ServiceReloadRequest();

// Deletes the C#-declared ConCommands and ConVars and their names. Only after
// the engine has unregistered this DLL's commands (ConVar_Unregister in
// DLLShutdown): until then its ICvar points at them.
void SourceSharp_ReleaseConsoleObjects();

#endif
