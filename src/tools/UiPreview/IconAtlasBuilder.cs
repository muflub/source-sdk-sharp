using System.Globalization;
using System.IO.Compression;
using System.Text;

using SkiaSharp;

using SourceSharp.Client.Ui.Toolkit;

namespace SourceSharp.UiPreview;

/// <summary>
/// THE ICON ATLAS BUILD (tools/ui-icons, `make ui-icons`): every SVG in
/// src/client/ui/icons rasterised with SkiaSharp at each of
/// <see cref="UiIconSet.PixelHeights"/>, white, alpha only, packed into rows
/// by height then name with a 2-pixel gutter, into src/client/ui/icons/atlas:
/// icons.tsv (the manifest: name, height, x, y, w, h) and icons.a8z (the alpha
/// bytes, zlib). Deterministic: the same SVGs give the same bytes, which the
/// facts hold to the committed files.
/// </summary>
public static class IconAtlasBuilder
{
    public const int AtlasWidth = 1024, Gutter = 2;

    public sealed record Atlas(string Manifest, byte[] Compressed, int Width, int Height, byte[] Alpha);

    public static string IconDir(string root) => Path.Combine(root, "src", "client", "ui", "icons");

    public static Atlas Build(string iconDir)
    {
        var icons = Directory.GetFiles(iconDir, "*.svg").Order(StringComparer.Ordinal)
            .Select(f => UiIconSet.ParseSvg(Path.GetFileNameWithoutExtension(f), File.ReadAllText(f)))
            .OrderBy(i => i.Name, StringComparer.Ordinal).ToArray();

        // Rasterise each icon at each height, then shelf-pack in that order.
        var pieces = new List<(string Name, int Height, int W, byte[] A)>();
        foreach (int h in UiIconSet.PixelHeights)
            foreach (var icon in icons)
                pieces.Add((icon.Name, h, (int)MathF.Ceiling(icon.Width * h / UiIconSet.GridHeight), Rasterise(icon, h)));

        var placed = new List<(int X, int Y)>();
        int x = Gutter, y = Gutter, rowH = 0;
        foreach (var p in pieces)
        {
            if (x + p.W + Gutter > AtlasWidth)
            {
                x = Gutter;
                y += rowH + Gutter;
                rowH = 0;
            }
            placed.Add((x, y));
            x += p.W + Gutter;
            rowH = Math.Max(rowH, p.Height);
        }
        int height = y + rowH + Gutter;

        var alpha = new byte[AtlasWidth * height];
        var manifest = new StringBuilder();
        manifest.Append("# src/client/ui/icons/atlas/icons.tsv: GENERATED by tools/ui-icons from the SVGs beside it. Do not edit.\n");
        manifest.Append("# name\theight\tx\ty\tw\th\n");
        manifest.Append(CultureInfo.InvariantCulture, $"atlas\t{AtlasWidth}\t{height}\n");
        for (int i = 0; i < pieces.Count; i++)
        {
            var (name, h, w, a) = pieces[i];
            var (px, py) = placed[i];
            for (int row = 0; row < h; row++)
                Array.Copy(a, row * w, alpha, (py + row) * AtlasWidth + px, w);
            manifest.Append(CultureInfo.InvariantCulture, $"{name}\t{h}\t{px}\t{py}\t{w}\t{h}\n");
        }

        using var compressed = new MemoryStream();
        using (var z = new ZLibStream(compressed, CompressionLevel.SmallestSize, leaveOpen: true))
            z.Write(alpha);
        return new Atlas(manifest.ToString(), compressed.ToArray(), AtlasWidth, height, alpha);
    }

    /// <summary>One icon <paramref name="height"/> pixels tall: alpha bytes, row by row, the icon's width.</summary>
    public static byte[] Rasterise(UiIconInfo icon, int height)
    {
        int w = (int)MathF.Ceiling(icon.Width * height / UiIconSet.GridHeight);
        using var bitmap = new SKBitmap(new SKImageInfo(w, height, SKColorType.Alpha8, SKAlphaType.Premul));
        using (var canvas = new SKCanvas(bitmap))
        using (var path = SKPath.ParseSvgPathData(icon.PathData) ?? throw new InvalidDataException($"{icon.Name}.svg: a path Skia cannot read"))
        using (var paint = new SKPaint { IsAntialias = true, Color = SKColors.White, Style = SKPaintStyle.Fill })
        {
            canvas.Clear(SKColors.Transparent);
            path.FillType = SKPathFillType.EvenOdd;
            float s = height / UiIconSet.GridHeight;
            canvas.Scale(s, s);
            canvas.DrawPath(path, paint);
        }
        return bitmap.Bytes.Length == w * height ? bitmap.Bytes : Repack(bitmap, w, height);
    }

    private static byte[] Repack(SKBitmap bitmap, int w, int h)
    {
        var src = bitmap.Bytes;
        var dst = new byte[w * h];
        for (int row = 0; row < h; row++)
            Array.Copy(src, row * bitmap.RowBytes, dst, row * w, w);
        return dst;
    }

    /// <summary>Writes the atlas beside the art, and a PNG of it (white on dark) under <paramref name="pngDir"/>.</summary>
    public static int Write(string root, string pngDir)
    {
        var atlas = Build(IconDir(root));
        string dir = Path.Combine(IconDir(root), "atlas");
        Directory.CreateDirectory(dir);
        File.WriteAllText(Path.Combine(dir, "icons.tsv"), atlas.Manifest);
        File.WriteAllBytes(Path.Combine(dir, "icons.a8z"), atlas.Compressed);
        Directory.CreateDirectory(pngDir);
        using (var bmp = new SKBitmap(atlas.Width, atlas.Height))
        {
            for (int y = 0; y < atlas.Height; y++)
                for (int x = 0; x < atlas.Width; x++)
                {
                    byte a = atlas.Alpha[y * atlas.Width + x];
                    bmp.SetPixel(x, y, new SKColor((byte)(30 + a * 225 / 255), (byte)(32 + a * 223 / 255), (byte)(36 + a * 219 / 255)));
                }
            using var data = bmp.Encode(SKEncodedImageFormat.Png, 100);
            File.WriteAllBytes(Path.Combine(pngDir, "icons-atlas.png"), data.ToArray());
        }
        Console.WriteLine($"ui-icons: {atlas.Width}x{atlas.Height} atlas, {atlas.Compressed.Length} bytes compressed -> {dir}");
        return 0;
    }
}
