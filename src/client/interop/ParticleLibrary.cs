namespace SourceSharp.Abi;

/// <summary>
/// The particle library's manager-wide reads (plan_particles_so.md): what
/// <c>g_pParticleSystemMgr</c> answers, asked of libss_particles.so directly.
/// Game thread.
/// </summary>
public interface IParticleLibrary
{
    /// <summary><c>CParticleSystemMgr::ParticleThrottleScaling</c>: 1 unrestricted .. 0 fully.</summary>
    float ThrottleScaling();

    /// <summary><c>CParticleSystemMgr::GetParticleSystemCount</c>: the definitions loaded.</summary>
    int SystemCount();

    /// <summary><c>CParticleSystemMgr::GetParticleSystemNameFromIndex</c>, or null past the end.</summary>
    string? SystemName(int index);
}

/// <summary>
/// ISSParticleLib through its vtable (ParticleLibVtbl, generated by
/// tools/vtable-layout from iparticlelib.h). The object is the library's own
/// singleton, served by the client's internal factory under
/// <c>SSParticleLib001</c>; client.so's particles.a forwards call the same
/// object. Bound on first use, so a reloaded assembly binds again; the library
/// is native and outlives every reload.
/// </summary>
internal sealed unsafe class ParticleLibrary(NativeInterfaceFactory factory) : IParticleLibrary
{
    public const string InterfaceVersion = "SSParticleLib001";

    // particles.a's longest system names are well under this; the name is
    // copied out of the library's own string table.
    private const int MaxName = 256;

    private void* _self;
    private ParticleLibVtbl* _vtbl;

    private ParticleLibVtbl* Vtbl
    {
        get
        {
            if (_vtbl == null)
                Bind();

            return _vtbl;
        }
    }

    private void Bind()
    {
        if (!Vtable.TryAcquireShim<ParticleLibVtbl>(
                factory, InterfaceVersion, out void* self, out void** table, out string why))
            throw InterfaceAcquisitionException.FromReport(
                SourceSharpFactoryType.Internal, InterfaceVersion, why);

        _self = self;
        _vtbl = (ParticleLibVtbl*)table;
    }

    private void* Manager => Vtbl->Mgr(_self);

    /// <inheritdoc/>
    public float ThrottleScaling() => Vtbl->MgrParticleThrottleScaling(_self, Manager);

    /// <inheritdoc/>
    public int SystemCount() => Vtbl->MgrGetParticleSystemCount(_self, Manager);

    /// <inheritdoc/>
    public string? SystemName(int index)
        => index >= 0 && index < SystemCount()
            ? Vtable.TextOf(Vtbl->MgrGetParticleSystemNameFromIndex(_self, Manager, index), MaxName)
            : null;
}
