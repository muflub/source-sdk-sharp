TEST_F( ClientInterpolation, TheStampIsTheWholeOfNoteNetworkedPosition )
{
	// It used to file the pose into two histories and take a teleport flag. It
	// is one store now: the packet's own server time, which is what the managed
	// rings key their "is there a new sample here" test off.
	const std::string &code = ClientShellCode();

	const size_t at = code.find( "void C_StandaloneEntity::NoteNetworkedPosition()" );
	ASSERT_NE( std::string::npos, at )
		<< "NoteNetworkedPosition is gone or has grown an argument back.";

	const size_t end = code.find( "\n}", at );
	ASSERT_NE( std::string::npos, end );

	const std::string body = code.substr( at, end - at );

	EXPECT_NE( std::string::npos, body.find( "Block().Client.SimulationTime = engine->GetLastTimeStamp();" ) )
		<< "the packet stamp is what the managed rings read; without it every "
		<< "entity looks unchanged forever and nothing is ever sampled.";

	// One statement. A second semicolon would be a second thing happening in a
	// function whose whole claim is that it does one.
	EXPECT_EQ( 1u, CountOf( body, ";" ) ) << body;
}

TEST_F( ClientInterpolation, PostInterpolateDoesTheTwoEngineThingsAndNoArithmetic )
{
	const std::string &code = ClientShellCode();

	const size_t at = code.find( "void C_StandaloneEntity::PostInterpolate( float flCurrentTime )" );
	ASSERT_NE( std::string::npos, at ) << "PostInterpolate is gone.";

	// FROM THE OPENING BRACE and not from the signature, which is not
	// pedantry: "PostInterpolate(" contains "Interpolate(", so a body search
	// that started at the declaration would match the function's own name and
	// the assertion below could never pass.
	const size_t open = code.find( '{', at );
	ASSERT_NE( std::string::npos, open );

	const size_t end = code.find( "\n}", open );
	ASSERT_NE( std::string::npos, end );

	const std::string body = code.substr( open, end - open );

	// OnPositionChanged is the transform rebuild and the leaf-system notify --
	// both engine calls, both staying where the engine is.
	EXPECT_NE( std::string::npos, body.find( "OnPositionChanged();" ) );

	// And nothing that blends anything.
	EXPECT_EQ( std::string::npos, body.find( "Interpolate(" ) );
	EXPECT_EQ( std::string::npos, body.find( "Lerp" ) );
}

