TEST_F( ClientInterpolation, InterpolatedVarLeftWithCBaseEntity )
{
	// plan_entity.md step 6a's last clause, closed by plan_client_novalve C8
	// (lane c6-input): the tripwire that stood here waited for
	// interpolatedvar.cpp to leave. Measured before it did: no object on the
	// client link line but its own instantiated CInterpolatedVar, and the only
	// import of its five strong definitions was shell_clientdll.cpp's
	// g_flLastPacketTimestamp write (Interpolation_SetLastPacketTimeStamp), a
	// global only CInterpolatedVar::NoteLastNetworkedValue read. Interpolation.cs
	// is the implementation, held to Fixtures/interpolation-stock.tsv
	// (InterpolationTests).
	ASSERT_TRUE( cmake_graph::Compiles( cmake_graph::kClient, kClientProofOfRead ) )
		<< "the reader is not reading client_sourcesharp's source list.";

	EXPECT_FALSE( cmake_graph::Compiles( cmake_graph::kClient, "game/client/c_baseentity.cpp" ) )
		<< "c_baseentity.cpp is back in the client build.";
	EXPECT_FALSE( cmake_graph::Compiles( cmake_graph::kClient, "game/client/interpolatedvar.cpp" ) )
		<< "interpolatedvar.cpp is back in the client build; Interpolation.cs is "
		<< "the implementation.";
}
