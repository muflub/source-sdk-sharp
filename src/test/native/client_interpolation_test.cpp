const char *SrcRoot()
{
	static const char *kCandidates[] = { ".", "src", "../src" };
	for ( size_t i = 0; i < sizeof( kCandidates ) / sizeof( kCandidates[ 0 ] ); i++ )
	{
		struct stat st;
		const std::string game = std::string( kCandidates[ i ] ) + "/game";
		const std::string pub = std::string( kCandidates[ i ] ) + "/public";
		if ( stat( game.c_str(), &st ) == 0 && S_ISDIR( st.st_mode )
			&& stat( pub.c_str(), &st ) == 0 && S_ISDIR( st.st_mode ) )
		{
			return kCandidates[ i ];
		}
	}
	return NULL;
}

std::string Read( const std::string &strRelative )
{
	const char *pszRoot = SrcRoot();
	if ( !pszRoot )
		return std::string();

	std::ifstream file( ( std::string( pszRoot ) + "/" + strRelative ).c_str() );
	if ( !file.is_open() )
		return std::string();

	return std::string( ( std::istreambuf_iterator< char >( file ) ),
	                    std::istreambuf_iterator< char >() );
}

// Blanks // and /* */ comments, keeping newlines so nothing else shifts.
//
// EVERY FACT BELOW READS THE STRIPPED TEXT, and that is not caution for its own
// sake: this file's own prose names CInterpolatedVar, m_iv_vecOrigin and
// Interpolate a dozen times, and so does the prose of the file it reads. A
// search over raw source would find the words in the comments explaining that
// they are gone.
std::string StripComments( const std::string &in )
{
	std::string out;
	out.reserve( in.size() );

	enum { kCode, kLine, kBlock } state = kCode;
	for ( size_t i = 0; i < in.size(); i++ )
	{
		if ( state == kCode )
		{
			if ( in[ i ] == '/' && i + 1 < in.size() && in[ i + 1 ] == '/' )
			{
				state = kLine; i++; continue;
			}
			if ( in[ i ] == '/' && i + 1 < in.size() && in[ i + 1 ] == '*' )
			{
				state = kBlock; i++; continue;
			}
			out += in[ i ];
		}
		else if ( state == kLine )
		{
			if ( in[ i ] == '\n' ) { state = kCode; out += '\n'; }
		}
		else
		{
			if ( in[ i ] == '*' && i + 1 < in.size() && in[ i + 1 ] == '/' )
			{
				state = kCode; i++;
			}
		}
	}
	return out;
}

size_t CountOf( const std::string &haystack, const std::string &needle )
{
	size_t n = 0;
	for ( size_t at = haystack.find( needle ); at != std::string::npos;
	      at = haystack.find( needle, at + needle.size() ) )
	{
		n++;
	}
	return n;
}

