TEST_F( ClientInterpolation, TheSlotIsWiredOnTheClientAndOnlyThere )
{
	// Wired = the client shim area's generated forward to the body.
	ASSERT_EQ( 1, ForwardCount( ClientForwards(), "ClientInterpBlocks", "SourceSharp_ClientInterpBlocks" ) )
		<< "the slot is declared and never wired.";

	// Inside the CLIENT_DLL arm: the file holding that forward is included
	// where only the client compiles it.
	const std::string &code = GameSystemCode();
	const size_t at = code.find( "\n#include \"shell_shim_areas_client.inc\"" );
	ASSERT_NE( std::string::npos, at );

	EXPECT_EQ( kOnClient, SidesAt( code, at + 1 ) )
		<< "the client's forwards, ClientInterpBlocks among them, are compiled "
		<< "outside the CLIENT_DLL arm; the server has no such list and "
		<< "SourceSharp_ClientInterpBlocks is not compiled into it.";

	// And not on the server's forwards either.
	EXPECT_EQ( 0, ForwardCount( ServerForwards(), "ClientInterpBlocks", "" ) )
		<< "ClientInterpBlocks is wired on the server, which has no such list.";
}

