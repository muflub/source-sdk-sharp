//========= SourceSharp — client interpolation is managed code ===============//
//
// plan_entity.md step 6a. `CInterpolatedVar` is 1591 lines of template that
// every standalone client entity carried two instantiations of; the history and
// the blend are managed rings now, and what is left on this side is a LIST and
// the after-effects of a pose changing.
//
// WHY THE CHECKS ARE TEXTUAL. The same reason 1b's and 5c's are: nothing in a
// build can see two implementations of one algorithm, both compiled, both
// reachable, one of them dead. A native `Interpolate` that quietly kept
// blending would compile, run, and produce a curve that fought the managed one
// on alternate frames — and the game would look nearly right.
//
// WHAT THIS FILE CANNOT SAY, said here rather than left implied: it cannot say
// the managed curve is the engine's curve. That is
// `SourceSharp.Tests/InterpolationTests`, replaying a recording of the C++ this
// removes, and this file's job is only that the C++ is actually gone and that
// the one thing left native is the one thing that has to be.
//
//=============================================================================//

