//========= SourceSharp — stock's variant_t answers, from the real libc =======//
//
// plan_entity.md moves `variant_t::Convert` into managed code: it lives in
// `game/server/cbase.cpp`, one of the 25 TUs the flip removes in a single
// commit, and §6 does not keep it native. `SourceSharp.Abi.VariantParse` is the
// replacement.
//
// THAT REPLACEMENT IS A STAND-IN FOR NATIVE CODE, AND A STAND-IN DRIFTS
// SILENTLY. It reimplements `atoi`, `atof`, two `sscanf` formats and two
// `snprintf` formats in C#, because those are what stock calls on a map's text
// and because C# does not answer what they answer — `float.TryParse` refuses
// "2x", knows nothing of "0x10", and cannot produce "%g". A wrong answer from
// any of them looks exactly like a map author's mistake: the map still loads,
// the entity still fires, and the number is different.
//
// So the table is asserted TWICE, over one file. `variant_convert_cases.tsv`
// holds every expected answer; this test recomputes each one with the libc the
// game links against, and `VariantAgreementTests` recomputes each one with
// `VariantParse`. Neither reads the other. A drift in the managed parser fails
// there, a drift in the platform fails here, and a hand-edited row fails both —
// which is why the file is generated by `tools/variant-oracle.c` rather than
// written.
//
// EVERY EXPRESSION BELOW IS COPIED OUT OF `variant_t::Convert` AND
// `variant_t::ToString`, not written afresh. The point of the file is that it
// is the same code, so a reader can put it beside cbase.cpp and see that it is.
//
//=============================================================================//

