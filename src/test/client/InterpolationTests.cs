    /// <summary>
    /// THE COUNT THAT IGNORES WHAT CAME BEFORE. A whole-window lag count
    /// carries the tail of anything the entity did before the step under
    /// measurement — on the live gate that read 19 lagging frames of a declared
    /// jump, every one of them the previous move finishing. Counting from the
    /// arrival is the only interval the claim is about.
    /// </summary>
    [Fact]
    public void TheSinceDeliveryCountIgnoresAMoveThatWasStillBeingDrawnOut()
    {
        (Interpolation interp, FakeBlocks blocks, byte[] block) = OneEntity();

        Deliver(interp, blocks, block, 1.0f, 1.0f, 0f, 0f, 0f, 0f);
        Deliver(interp, blocks, block, 1.1f, 1.1f, 20f, 0f, 0f, 0f);

        // Watching opens mid-slide: the 20-unit move is still being drawn out.
        interp.Watch(4);
