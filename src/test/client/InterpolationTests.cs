    [Fact]
    public void TheManagedRingsReproduceEveryRecordedAngle()
    {
        Replay r = Replayed.Value;

        // NOT BIT FOR BIT, AND THE REASON IS NAMED RATHER THAN PAPERED OVER.
        // An angle is blended through quaternions: AngleQuaternion calls sinf
        // and cosf, QuaternionSlerpNoAlign calls acos and sin, and
        // QuaternionAngles ends in three atan2f. Those are the platform's libm
        // in the C++ and the runtime's in the C#, and nothing in this port can
        // make two libms agree in the last bit. What CAN be required is that
        // the disagreement stay at the size of a rounding error -- a wrong
        // blend fraction, a wrong pair of samples or a missing time fixup all
        // move an angle by degrees, not by millionths of one.
        // MEASURED, not chosen: the worst disagreement over the whole fixture is
        // 3.81e-05 degrees, which is about three ulp of a float at 90. The bound
        // is 1e-4 -- under three times that -- so a real algorithmic error, which
        // moves an angle by degrees, cannot hide under it.
        Assert.True(r.WorstAngleDelta < 1e-4f,
            $"worst angle difference {r.WorstAngleDelta} degrees at {r.WorstAngleWhere}");
    }

