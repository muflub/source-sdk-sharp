    /// <summary>
    /// The offsets, worked out from the block rather than read off the same
    /// reflection the code under test uses.
    /// </summary>
    private static class EngineBlockOffsets
    {
        private static int Head(string field)
            => (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlock>(nameof(EngineBlock.Head))
             + (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlockHead>(field);

        private static int Tail(string field)
            => (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlock>(nameof(EngineBlock.Client))
             + (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlockClientTail>(field);

        public static int Origin => Head(nameof(EngineBlockHead.Origin));
        public static int Angles => Head(nameof(EngineBlockHead.Angles));
        public static int RenderOrigin => Tail(nameof(EngineBlockClientTail.RenderOrigin));
        public static int RenderAngles => Tail(nameof(EngineBlockClientTail.RenderAngles));
    }

