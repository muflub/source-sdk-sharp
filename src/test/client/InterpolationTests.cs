    /// <summary>One <c>Interpolate</c> call and the pose the engine produced.</summary>
    private sealed record Call(int Line, uint Handle, float CurrentTime, float InterpolationAmount,
                               bool ExtrapolationAllowed,
                               float[] InOrigin, float[] InAngles,
                               float[] OutOrigin, float[] OutAngles);

    /// <summary>One networked sample, at the moment it was filed.</summary>
    private sealed record Sample(int Line, uint Handle, float CurTime, float ChangeTime,
                                 float InterpolationAmount, bool Teleported,
                                 float[] Origin, float[] Angles);

    /// <summary>One history entry as it stood when the recorder armed.</summary>
    private sealed record Seed(uint Handle, int Index, float OriginTime, float AngleTime,
                               float[] Origin, float[] Angles);

    private sealed record Fixture(float ExtrapolateAmount, float InterpAmount, float TickInterval,
                                  List<(uint Handle, int EntIndex, string ClassName, bool WantsInterp)> Entities,
                                  List<Seed> Seeds, List<object> Events);

    private static float F(string text)
        => float.Parse(text, NumberStyles.Float, CultureInfo.InvariantCulture);

    private static float[] V(string[] c, int at) => [F(c[at]), F(c[at + 1]), F(c[at + 2])];

    private static Fixture Stock()
    {
        string path = Path.Combine(RepoLayout.SdkTree, "src", "sourcesharp", "managed",
                                   "SourceSharp.Tests", "Fixtures",
                                   "interpolation-stock.tsv");

        Assert.True(File.Exists(path), "the recorded stock interpolation is missing: " + path);

        float extrapolate = 0f, interp = 0f, tick = 0f;
        var entities = new List<(uint, int, string, bool)>();
        var seeds = new List<Seed>();
        var events = new List<object>();

        string[] lines = File.ReadAllLines(path);

        for (int i = 0; i < lines.Length; i++)
        {
            if (lines[i].Length == 0 || lines[i][0] == '#')
                continue;

            string[] c = lines[i].Split('\t');
            Assert.True(c[0] == "SS6A", $"line {i + 1} is not a probe row");

            switch (c[1])
            {
                case "CV":
                    Assert.True(c.Length == 5, $"line {i + 1}: CV has {c.Length} columns, not 5");
                    extrapolate = F(c[2]);
                    interp = F(c[3]);
                    tick = F(c[4]);
                    break;

                case "AR":
                    Assert.True(c.Length == 6, $"line {i + 1}: AR has {c.Length} columns, not 6");
                    entities.Add((uint.Parse(c[2], CultureInfo.InvariantCulture),
                                  int.Parse(c[3], CultureInfo.InvariantCulture),
                                  c[4], c[5] == "1"));
                    break;

                case "AH":
                    Assert.True(c.Length == 12, $"line {i + 1}: AH has {c.Length} columns, not 12");
                    seeds.Add(new Seed(uint.Parse(c[2], CultureInfo.InvariantCulture),
                                       int.Parse(c[3], CultureInfo.InvariantCulture),
                                       F(c[4]), F(c[5]), V(c, 6), V(c, 9)));
                    break;

                case "N":
                    Assert.True(c.Length == 14, $"line {i + 1}: N has {c.Length} columns, not 14");
                    events.Add(new Sample(i + 1, uint.Parse(c[2], CultureInfo.InvariantCulture),
                                          F(c[3]), F(c[4]), F(c[5]), c[6] == "1",
                                          V(c, 7), V(c, 10)));
                    break;

                case "I":
                    Assert.True(c.Length == 19, $"line {i + 1}: I has {c.Length} columns, not 19");
                    events.Add(new Call(i + 1, uint.Parse(c[2], CultureInfo.InvariantCulture),
                                        F(c[3]), F(c[4]), c[5] == "1",
                                        V(c, 7), V(c, 10), V(c, 13), V(c, 16)));
                    break;

                default:
                    Assert.Fail($"line {i + 1}: unknown row kind '{c[1]}'");
                    break;
            }
        }

        return new Fixture(extrapolate, interp, tick, entities, seeds, events);
    }

    //-------------------------------------------------------------------------
    // The replay.
    //-------------------------------------------------------------------------

    /// <summary>What one replay produced, so several facts can read one run.</summary>
    private sealed class Replay
    {
        public Fixture Fixture = null!;
        public Interpolation Interp = null!;
        public int Calls;
        public int OriginMismatches;
        public float WorstOriginDelta;
        public float WorstAngleDelta;
        public string WorstOriginWhere = "";
        public string WorstAngleWhere = "";
    }

    private const int OriginField = 0;
    private const int AnglesField = 1;

    private static int SlotOf(uint handle) => (int)(handle & Interpolation.EntryMask);

    private static Replay Run()
    {
        var replay = new Replay { Fixture = Stock(), Interp = new Interpolation() };
        Interpolation interp = replay.Interp;

        // The rings, seeded from the history the entities actually had when the
        // recorder armed. Oldest first, because AddToHead is what fills them and
        // the fixture lists them newest first.
        foreach (var group in replay.Fixture.Seeds.GroupBy(s => s.Handle))
        {
            int slot = SlotOf(group.Key);
            interp.Rebind(slot, group.Key);

            foreach (Seed seed in group.OrderByDescending(s => s.Index))
            {
                interp.RingFor(slot, OriginField)
                      .AddToHead(seed.OriginTime, seed.Origin[0], seed.Origin[1], seed.Origin[2], false);
                interp.RingFor(slot, AnglesField)
                      .AddToHead(seed.AngleTime, seed.Angles[0], seed.Angles[1], seed.Angles[2], false);
            }
        }

        Span<InterpolationSample> values = stackalloc InterpolationSample[2];

        foreach (object e in replay.Fixture.Events)
        {
            if (e is Sample s)
            {
                values[OriginField] = new InterpolationSample(0f, s.Origin[0], s.Origin[1], s.Origin[2]);
                values[AnglesField] = new InterpolationSample(0f, s.Angles[0], s.Angles[1], s.Angles[2]);

                interp.NoteNetworked(SlotOf(s.Handle), s.Handle, s.ChangeTime,
                                     s.InterpolationAmount, s.CurTime, s.Teleported, values);
                continue;
            }

            var call = (Call)e;
            replay.Calls++;

            // The recording says extrapolation was never allowed. If a later
            // recording DOES allow it, this replay must stop pretending
            // otherwise -- so the flag is read rather than assumed.
            Assert.False(call.ExtrapolationAllowed,
                $"line {call.Line}: the fixture reached the extrapolation arm, which the replay does not model");

            int slot = SlotOf(call.Handle);

            interp.Interpolate(slot, OriginField, call.CurrentTime, call.InterpolationAmount,
                               out InterpolationSample origin);
            interp.Interpolate(slot, AnglesField, call.CurrentTime, call.InterpolationAmount,
                               out InterpolationSample angles);

            float[] gotOrigin = [origin.A, origin.B, origin.C];
            float[] gotAngles = [angles.A, angles.B, angles.C];

            for (int k = 0; k < 3; k++)
            {
                if (!gotOrigin[k].Equals(call.OutOrigin[k]))
                {
                    replay.OriginMismatches++;

                    float delta = MathF.Abs(gotOrigin[k] - call.OutOrigin[k]);
                    if (delta > replay.WorstOriginDelta)
                    {
                        replay.WorstOriginDelta = delta;
                        replay.WorstOriginWhere =
                            $"line {call.Line} component {k}: got {gotOrigin[k]:R}, stock {call.OutOrigin[k]:R}";
                    }
                }

                float angleDelta = MathF.Abs(AngleDifference(gotAngles[k], call.OutAngles[k]));
                if (angleDelta > replay.WorstAngleDelta)
                {
                    replay.WorstAngleDelta = angleDelta;
                    replay.WorstAngleWhere =
                        $"line {call.Line} component {k}: got {gotAngles[k]:R}, stock {call.OutAngles[k]:R}";
                }
            }
        }

        return replay;
    }

    /// <summary>Degrees apart, the short way round — 359.9 and −0.1 are 0.2 apart.</summary>
    private static float AngleDifference(float a, float b)
    {
        float d = (a - b) % 360f;
        if (d > 180f) d -= 360f;
        if (d < -180f) d += 360f;
        return d;
    }

    private static readonly Lazy<Replay> Replayed = new(Run);

