    [Fact]
    public void TheRecordingContainsAStep()
    {
        // "A stepped input" is the gate's phrase and this is what makes it true
        // of the fixture: an entity whose networked position jumps by whole
        // units between consecutive samples, which is what the client is
        // smoothing over.
        var bySlot = Stock().Events.OfType<Sample>()
            .GroupBy(s => s.Handle)
            .Select(g => g.OrderBy(s => s.ChangeTime).ToArray());

        float biggest = 0f;

        foreach (var samples in bySlot)
        {
            for (int i = 1; i < samples.Length; i++)
            {
                float dx = samples[i].Origin[0] - samples[i - 1].Origin[0];
                float dy = samples[i].Origin[1] - samples[i - 1].Origin[1];
                float dz = samples[i].Origin[2] - samples[i - 1].Origin[2];
                biggest = MathF.Max(biggest, MathF.Sqrt(dx * dx + dy * dy + dz * dz));
            }
        }

        Assert.True(biggest > 1.0f, $"the largest networked step in the fixture is {biggest} units");
    }

