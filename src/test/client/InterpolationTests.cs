    /// <summary>
    /// A CREATE IS NOT A TELEPORT, and this is the fact that says the two
    /// conditions are separate. An entity arriving in a slot with a non-zero
    /// counter — which any recycled index can — is <c>fresh</c>, and the pass
    /// must not also bill it as a jump.
    /// </summary>
    [Fact]
    public void ACreateIsCountedAsASlotRebindAndNotAsATeleport()
    {
        var interp = new Interpolation();
        var blocks = new FakeBlocks();
        byte[] block = blocks.Add(Handle);

        TeleportDiscontinuity.Bump(block.AsSpan(), out _);
        Deliver(interp, blocks, block, 1.0f, 1.0f, 0f, 0f, 0f, 0f);

        Assert.Equal(1, interp.SlotsRebound);
        Assert.Equal(1, interp.Teleported);

        // ...and the ring was seeded once, not reset twice: the drawn pose is
        // the arriving one either way, so what this asserts is that the second
        // pass over the same entity does nothing.
        Assert.Equal(0, interp.SamplePass(blocks, 1.0f));
    }

    /// <summary>
    /// THE SKIP THAT COULD HAVE SWALLOWED IT. The pass skips an entity whose
    /// simulation time did not move, because that is how it knows the packet did
    /// not carry it. A jump is exempt: it should never matter, since a jump
    /// moves the origin and an origin that moved came with a new time, but an
    /// entity left sliding for the rest of the map is a bad price for a
    /// comparison.
    /// </summary>
    [Fact]
    public void ATeleportIsNotSwallowedByTheUnchangedSimulationTimeSkip()
    {
        (Interpolation interp, FakeBlocks blocks, byte[] block) = OneEntity();

        Deliver(interp, blocks, block, 1.0f, 1.0f, 0f, 0f, 0f, 0f);

        TeleportDiscontinuity.Bump(block.AsSpan(), out _);
        PutTriple(block, HeadOffset(nameof(EngineBlockHead.Origin)), 500f, 0f, 0f);

        // Same packet time as before: the skip's own condition.
        Assert.Equal(1, interp.SamplePass(blocks, 1.05f));
        Assert.Equal(1, interp.Teleported);
    }

    //-------------------------------------------------------------------------
    // THE GATE'S OWN INSTRUMENT (cs_cl_teleport_watch / cs_cl_teleport_report,
    // driven live by tools/defect-teleport-gate).
    //
    // The gate is a rendered measurement on a running game and cannot be run
    // here. What CAN be run here is the instrument itself, over the same two
    // arms, so that "the probe read zero" is a claim about the build rather
    // than about the probe: a broken instrument reads zero on both arms and a
    // live gate cannot tell that from a fix.
    //-------------------------------------------------------------------------

    /// <summary>
    /// Renders <paramref name="frames"/> frames after an update, over the
    /// interpolation window, and answers what the probe saw.
    /// </summary>
    private static void RenderWindow(Interpolation interp, FakeBlocks blocks,
                                     float from, int frames)
    {
        for (int i = 0; i < frames; i++)
            interp.RenderPass(blocks, from + 0.01f * i);
    }

    [Fact]
    public void TheProbeReadsLaggingFramesForAJourneyThatWasNotDeclaredAJump()
    {
        (Interpolation interp, FakeBlocks blocks, byte[] block) = OneEntity();

        Deliver(interp, blocks, block, 1.0f, 1.0f, 0f, 0f, 0f, 0f);
        interp.Watch(4);
        Deliver(interp, blocks, block, 1.1f, 1.1f, 500f, 0f, 0f, 0f);

        RenderWindow(interp, blocks, 1.1f, 8);

        Assert.True(interp.WatchFrames >= 8, $"the probe saw {interp.WatchFrames} frames");
        Assert.True(interp.WatchLagging > 0,
            "THE INSTRUMENT IS BLIND: a 500-unit journey with nothing saying it was a jump "
          + "must be drawn short of its destination on some frame, or the gate's control "
          + "arm proves nothing");
        Assert.True(interp.WatchMaxLag > 100f, $"max lag {interp.WatchMaxLag}");
    }

    [Fact]
    public void TheProbeReadsNoLaggingFrameForTheSameJourneyDeclaredAJump()
    {
        (Interpolation interp, FakeBlocks blocks, byte[] block) = OneEntity();

