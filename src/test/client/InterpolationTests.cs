    /// <summary>A block list backed by managed byte arrays, standing in for the engine's.</summary>
    private sealed class FakeBlocks : IInterpolationBlocks
    {
        public readonly List<byte[]> Blocks = new();
        public float InterpolationAmount = 0.1f;
        public int Begins;

        public byte[] Add(uint handle)
        {
            var block = new byte[EngineBlock.SizeBytes];
            BitConverter.TryWriteBytes(block.AsSpan(0, 4), handle);
            Blocks.Add(block);
            return block;
        }

        public int Begin(out float interpolationAmount)
        {
            Begins++;
            interpolationAmount = InterpolationAmount;
            return Blocks.Count;
        }

        public Span<byte> Block(int index) => Blocks[index].AsSpan();
    }

    private static int HeadOffset(string field)
        => (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlock>(nameof(EngineBlock.Head))
         + (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlockHead>(field);

    private static int TailOffset(string field)
        => (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlock>(nameof(EngineBlock.Client))
         + (int)System.Runtime.InteropServices.Marshal.OffsetOf<EngineBlockClientTail>(field);

    private static void PutTriple(byte[] block, int offset, float a, float b, float c)
    {
        BitConverter.TryWriteBytes(block.AsSpan(offset, 4), a);
        BitConverter.TryWriteBytes(block.AsSpan(offset + 4, 4), b);
        BitConverter.TryWriteBytes(block.AsSpan(offset + 8, 4), c);
    }

    private static float[] GetTriple(byte[] block, int offset)
        => [BitConverter.ToSingle(block, offset),
            BitConverter.ToSingle(block, offset + 4),
            BitConverter.ToSingle(block, offset + 8)];

    /// <summary>Handle 4 with serial 1: entry index 4, and not the default 0.</summary>
    private const uint Handle = 4u | (1u << 16);

    private static (Interpolation, FakeBlocks, byte[]) OneEntity()
    {
        var interp = new Interpolation();
        var blocks = new FakeBlocks();
        byte[] block = blocks.Add(Handle);
        return (interp, blocks, block);
    }

    private static void Deliver(Interpolation interp, FakeBlocks blocks, byte[] block,
                                float packetTime, float curTime,
                                float x, float y, float z, float yaw)
    {
        PutTriple(block, HeadOffset(nameof(EngineBlockHead.Origin)), x, y, z);
        PutTriple(block, HeadOffset(nameof(EngineBlockHead.Angles)), 0f, yaw, 0f);
        BitConverter.TryWriteBytes(
            block.AsSpan(TailOffset(nameof(EngineBlockClientTail.SimulationTime)), 4), packetTime);

        interp.SamplePass(blocks, curTime);
    }

