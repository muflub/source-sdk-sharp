    /// <summary>
    /// <b>The interpolated pose IS the entity's position on the client</b>, so
    /// the render pass writes the head as well as the tail.
    ///
    /// <para>
    /// THE NAME AND THE REASON BOTH CHANGED IN STEP 6b, and the fact did not.
    /// It used to be <c>…BecauseTheTransformIsStillBuiltFromIt</c>: both
    /// <c>RenderableToWorldTransform</c> and <c>CollisionToWorldTransform</c>
    /// returned <c>Head.WorldTransform</c>, so leaving the head on the last
    /// snapshot would have stopped the renderer interpolating at all. 6b gave
    /// the tail a transform of its own, which removes that reason — and the head
    /// write stays anyway, for the reason that was underneath it: stock
    /// interpolates <c>m_vecOrigin</c> itself, and <c>C_BaseEntity</c>'s
    /// <c>GetRenderOrigin</c> and <c>CollisionProp</c>'s <c>GetCollisionOrigin</c>
    /// both answer <c>GetAbsOrigin</c>. Client collision follows the DRAWN pose
    /// in stock; a head left on the networked one would be a divergence rather
    /// than a tidier split.
    /// </para>
    ///
    /// <para>
    /// What the tail's own transform is FOR is a renderable drawn somewhere it
    /// is not — and today that is the viewmodel's eye pin, which writes the tail
    /// alone. See <c>ClientRenderTail.TheEyePinWritesTheTailAndLeavesTheHeadAlone</c>.
    /// </para>
    /// </summary>
    [Fact]
    public void TheRenderPassAlsoWritesTheHeadBecauseThatIsWhereStockInterpolates()
    {
        (Interpolation interp, FakeBlocks blocks, byte[] block) = OneEntity();

        Deliver(interp, blocks, block, 1.0f, 1.0f, 0f, 0f, 0f, 0f);
        Deliver(interp, blocks, block, 1.1f, 1.1f, 100f, 0f, 0f, 0f);

        interp.RenderPass(blocks, 1.15f);

        float[] head = GetTriple(block, HeadOffset(nameof(EngineBlockHead.Origin)));
        Assert.True(MathF.Abs(head[0] - 50f) < 0.01f, $"the head holds {head[0]}, not the drawn pose");

        // And the two hold the SAME value. What step 6b split was the
        // TRANSFORM, not the pose: RenderableToWorldTransform answers the
        // tail's matrix now and CollisionToWorldTransform the head's, so a
        // renderable CAN be drawn where it is not — the pose is only equal here
        // because nothing on this path asked for it to differ.
        float[] rendered = GetTriple(block, TailOffset(nameof(EngineBlockClientTail.RenderOrigin)));
        Assert.Equal(rendered[0], head[0]);
    }

