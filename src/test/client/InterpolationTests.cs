    [Fact]
    public void TheReplayNeverClampsTheFraction()
    {
        // MIN( frac, 2.0f ), interpolatedvar.h:846, IS DEAD CODE -- in stock as
        // well as here, and that is an argument rather than an observation.
        // GetInterpolationInfo only computes a fraction at the index where the
        // target is at or past `older`, and `newer` was set on the previous
        // iteration precisely because the target was BEFORE it. The ring's
        // timestamps are monotonically decreasing (AddToHead either flushes what
        // is newer or inserts in order), so the target is bracketed and the
        // fraction is in [0, 1). The clamp is ported because the arm is ported,
        // and this says so rather than leaving a reader to wonder.
        Assert.Equal(0, Replayed.Value.Interp.Arms.FractionOverOne);
    }

    [Fact]
    public void TheReplayReachesNoSingleSampleExit()
    {
        // The last exit of GetInterpolationInfo needs `newer` still unset after
        // the loop, and the loop sets it for every entry newer than the target.
        // The one way through is the `older_change_time == 0.0f` break -- an
        // entry whose timestamp is literally zero, which nothing in a live
        // recording files. Ported, counted, and zero.
        Assert.Equal(0, Replayed.Value.Interp.Arms.SingleSample);
    }

    [Fact]
    public void TheReplayReachesNoExtrapolation()
    {
        // interpolatedvar.h:960 guards the arm with
        // CInterpolationContext::IsExtrapolationAllowed(), which is false unless
        // something on the stack made a CInterpolationContext AND called
        // EnableExtrapolation(true). The standalone client's interpolation pass
        // made no context, so the flag was false for every one of the 10,380
        // Interpolate calls the raw recording holds.
        Assert.Equal(0, Replayed.Value.Interp.Arms.Extrapolated);
    }

