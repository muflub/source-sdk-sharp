    private static InterpolationRing VectorRing(out InterpolationArms arms)
    {
        arms = new InterpolationArms();
        return new InterpolationRing(InterpolationKind.Vector, arms);
    }

    [Fact]
    public void ASampleStampedEarlierThanTheHeadFlushesWhatIsNewerThanIt()
    {
        InterpolationRing ring = VectorRing(out InterpolationArms arms);

        ring.AddToHead(1.0f, 0, 0, 0, false);
        ring.AddToHead(2.0f, 10, 0, 0, false);
        Assert.Equal(2, ring.Count);

        // The server corrected the clock backwards: this sample is older than
        // the one already at the head.
        ring.AddToHead(1.5f, 20, 0, 0, true);

        Assert.Equal(1, arms.FlushedNewer);
        Assert.Equal(2, ring.Count);
        Assert.Equal(1.5f, ring[0].ChangeTime);
        Assert.Equal(1.0f, ring[1].ChangeTime);
    }

    [Fact]
    public void ARingThatOverflowsDropsTheOldestAndSaysSo()
    {
        InterpolationRing ring = VectorRing(out InterpolationArms arms);

        for (int i = 0; i <= InterpolationRing.Capacity; i++)
            ring.AddToHead(i + 1, i, 0, 0, false);

        Assert.Equal(1, arms.RingOverflowed);
        Assert.Equal(InterpolationRing.Capacity, ring.Count);

        // The newest survived and the oldest went.
        Assert.Equal(InterpolationRing.Capacity + 1f, ring[0].ChangeTime);
        Assert.Equal(2f, ring[^1].ChangeTime);
    }

    [Fact]
    public void AnEmptyRingAnswersNothingRatherThanZero()
    {
        InterpolationRing ring = VectorRing(out InterpolationArms arms);

        Assert.False(ring.Interpolate(1.0f, 0.1f, false, 0.25f, out _, out _, out _));
        Assert.Equal(1, arms.Empty);
    }

    [Fact]
    public void AResetSeedsThreeEntriesAtTheSameTime()
    {
        InterpolationRing ring = VectorRing(out InterpolationArms arms);

        ring.AddToHead(1.0f, 99, 99, 99, false);
        ring.Reset(5.0f, 1, 2, 3);

        Assert.Equal(1, arms.Teleported);
        Assert.Equal(3, ring.Count);

        for (int i = 0; i < 3; i++)
        {
            Assert.Equal(5.0f, ring[i].ChangeTime);
            Assert.Equal(1f, ring[i].A);
        }
    }

    [Fact]
    public void TwoSamplesEitherSideOfTheTargetBlendLinearly()
    {
        InterpolationRing ring = VectorRing(out InterpolationArms arms);

        ring.AddToHead(1.0f, 0, 0, 0, false);
        ring.AddToHead(2.0f, 100, 0, 0, false);

        // interp 0.5 at currentTime 2.0 -> target 1.5, halfway between them.
        Assert.True(ring.Interpolate(2.0f, 0.5f, false, 0.25f, out float x, out _, out _));

        Assert.Equal(1, arms.Linear);
        Assert.Equal(0, arms.Hermite);
